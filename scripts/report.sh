#!/usr/bin/env bash
# scripts/report.sh — Generate a per-stage report after each backend task execution.
# Usage: report.sh <stage> <module> <exit_code> <log_file> [--extra-metrics "<key>=<value> ..."]
#
# Writes a Markdown report to:
#   MyDesign/<Module>/workspace/reports/<stage>_<YYYYMMDD_HHMMSS>.md
set -euo pipefail
source "$(dirname "$0")/_common.sh"

# --- Argument parsing ---
STAGE="${1:-}"
MODULE="${2:-}"
EXIT_CODE="${3:-}"
LOG_FILE="${4:-}"
shift 4 || true

EXTRA_METRICS=""
while [[ $# -ge 2 ]]; do
  if [[ "$1" == "--extra-metrics" ]]; then
    EXTRA_METRICS="$2"
    shift 2
  else
    shift 1
  fi
done

if [[ -z "$STAGE" || -z "$MODULE" || -z "$EXIT_CODE" || -z "$LOG_FILE" ]]; then
  echo "Usage: report.sh <stage> <module> <exit_code> <log_file> [--extra-metrics \"key=value ...\"]" >&2
  exit 1
fi

# --- Path resolution ---
if [[ "$MODULE" == */* ]]; then
  MODULE_BASENAME=$(basename "$MODULE")
  case "$MODULE" in
    /*) BASE_DIR="$MODULE" ;;
    *)  BASE_DIR="$PLUGIN_ROOT/$MODULE" ;;
  esac
else
  MODULE_BASENAME="$MODULE"
  BASE_DIR="$PLUGIN_ROOT/MyDesign/$MODULE"
fi

REPORTS_DIR="$BASE_DIR/workspace/reports"
mkdir -p "$REPORTS_DIR"

# --- Timestamp ---
TIMESTAMP=$(date -Iseconds 2>/dev/null || date "+%Y-%m-%dT%H:%M:%S%z")
TIMESTAMP_SHORT=$(echo "$TIMESTAMP" | sed 's/[:-]//g' | sed 's/+//' | sed 's/T/_/' | cut -c1-16)
REPORT_FILE="$REPORTS_DIR/${STAGE}_${TIMESTAMP_SHORT}.md"

# --- Status ---
if [[ "$EXIT_CODE" == "0" ]]; then
  STATUS="✅ PASSED"
else
  STATUS="❌ FAILED"
fi

# --- Extract log excerpt ---
extract_log_excerpt() {
  local log="$1"
  local max_lines=60
  if [[ ! -f "$log" || ! -s "$log" ]]; then
    echo "(log file not available or empty)"
    return
  fi

  local total_lines
  total_lines=$(wc -l < "$log")

  if [[ "$total_lines" -le $max_lines ]]; then
    cat "$log"
  else
    echo "--- Log excerpt (first $max_lines of $total_lines lines) ---"
    head -n 30 "$log"
    echo "..."
    echo "--- Last $max_lines lines ---"
    tail -n 30 "$log"
  fi
}

# --- Extract key metrics from log ---
extract_compile_metrics() {
  local log="$1"
  if [[ ! -f "$log" ]]; then return; fi

  # Extract file count
  local sv_count
  sv_count=$(find "$(dirname "$log")" -maxdepth 1 \( -name "*.sv" -o -name "*.v" \) 2>/dev/null | wc -l)
  if [[ "$sv_count" -gt 0 ]]; then
    echo "| Verilog files emitted | $sv_count |"
  fi
}

extract_lint_metrics() {
  local log="$1"
  if [[ ! -f "$log" ]]; then return; fi

  local warn_count
  warn_count=$(wc -l < "$log" 2>/dev/null || echo "0")
  echo "| Warning count | $warn_count |"
}

extract_sim_metrics() {
  local log="$1"
  if [[ ! -f "$log" ]]; then return; fi

  local pass_count fail_count
  pass_count=$(grep -c "PASS" "$log" 2>/dev/null || echo "0")
  fail_count=$(grep -c "FAIL" "$log" 2>/dev/null || echo "0")
  echo "| Test cases PASS | $pass_count |"
  echo "| Test cases FAIL | $fail_count |"
}

# --- Build metrics section ---
build_extra_metrics() {
  local result=""
  if [[ -n "$EXTRA_METRICS" ]]; then
    while IFS='=' read -r key value; do
      result+="| $key | $value |"$'\n'
    done <<< "$EXTRA_METRICS"
  fi
  echo "$result"
}

# --- Write report ---
{
  echo "# $STAGE Report — $MODULE_BASENAME — $TIMESTAMP"
  echo ""
  echo "## Summary"
  echo ""
  echo "| Field | Value |"
  echo "|-------|-------|"
  echo "| Stage | \`$STAGE\` |"
  echo "| Module | \`$MODULE_BASENAME\` |"
  echo "| Status | $STATUS |"
  echo "| Exit code | \`$EXIT_CODE\` |"
  echo "| Timestamp | $TIMESTAMP |"

  # Stage-specific metrics
  case "$STAGE" in
    compile)
      extract_compile_metrics "$LOG_FILE"
      ;;
    lint)
      extract_lint_metrics "$LOG_FILE"
      ;;
    simulate)
      extract_sim_metrics "$LOG_FILE"
      ;;
  esac

  # Extra metrics from caller
  build_extra_metrics

  echo ""
  echo "<!-- expand: detailed-log -->"
  echo "<details>"
  echo "<summary>📋 Detailed log (click to expand)</summary>"
  echo ""
  echo '```'
  extract_log_excerpt "$LOG_FILE"
  echo '```'
  echo "</details>"
  echo ""
  echo "<!-- expand: raw-metrics -->"
  echo "<details>"
  echo "<summary>📊 Stage-specific metrics (click to expand)</summary>"
  echo ""
  echo "| Metric | Value |"
  echo "|--------|-------|"

  case "$STAGE" in
    compile)
      echo "| Generated files | see Summary |"
      ;;
    lint)
      echo "| Warnings captured | see Summary |"
      ;;
    simulate)
      echo "| Test results | see Summary |"
      ;;
    *)
      echo "| Log file | \`$LOG_FILE\` |"
      ;;
  esac

  echo "</details>"
  echo ""
  echo "---"
  echo "*Report generated by ChipAgent — $TIMESTAMP*"

} > "$REPORT_FILE"

echo "Report written: $REPORT_FILE"
