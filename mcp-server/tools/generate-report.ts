import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";

interface WorkspaceConfig {
  workspace_dir: string;
  backend_mode: string;
  docker_results_dir?: string;
  orfs_flow_path?: string;
}

function readWorkspaceConfig(): WorkspaceConfig | null {
  try {
    const configPath = join(homedir(), ".chipagent", "workspace.json");
    if (!existsSync(configPath)) return null;
    const content = readFileSync(configPath, "utf-8");
    return JSON.parse(content) as WorkspaceConfig;
  } catch {
    return null;
  }
}

function resolveWorkspaceDir(): string {
  const config = readWorkspaceConfig();
  if (config?.workspace_dir) return config.workspace_dir;
  // Fallback: derive from script location
  return "";
}

function resolveModuleWorkspace(moduleName: string): string {
  const workspaceDir = resolveWorkspaceDir();
  if (workspaceDir) return join(workspaceDir, "MyDesign", moduleName);
  return "";
}

function timestamp(): string {
  const now = new Date();
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}_${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;
}

function formatMetricsTable(metrics: Record<string, string | number | null | undefined>): string {
  const rows: string[] = [];
  for (const [key, value] of Object.entries(metrics)) {
    if (value !== undefined && value !== null) {
      rows.push(`| ${key} | ${value} |`);
    }
  }
  return rows.join("\n");
}

function escapeMarkdown(text: string): string {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function buildMarkdownReport(params: {
  stage: string;
  moduleName: string;
  success: boolean;
  exitCode: number | null;
  metrics?: Record<string, string | number | null | undefined>;
  logExcerpt?: string;
  errorDetails?: string;
}): string {
  const { stage, moduleName, success, exitCode, metrics, logExcerpt, errorDetails } = params;
  const ts = timestamp();
  const status = success ? "✅ PASSED" : "❌ FAILED";
  const statusField = success ? "PASSED" : "FAILED";

  const lines: string[] = [];
  lines.push(`# PnR Report — ${stage} — ${moduleName} — ${ts}`);
  lines.push("");
  lines.push("## Summary");
  lines.push("");
  lines.push("| Field | Value |");
  lines.push("|-------|-------|");
  lines.push(`| Stage | \`${stage}\` |`);
  lines.push(`| Module | \`${moduleName}\` |`);
  lines.push(`| Status | ${status} |`);
  lines.push(`| Exit code | \`${exitCode ?? "N/A"}\` |`);
  lines.push(`| Timestamp | ${ts} |`);

  if (metrics && Object.keys(metrics).length > 0) {
    lines.push("");
    lines.push("## Metrics");
    lines.push("");
    lines.push("| Metric | Value |");
    lines.push("|--------|-------|");
    lines.push(formatMetricsTable(metrics));
  }

  if (logExcerpt) {
    const escapedExcerpt = escapeMarkdown(logExcerpt);
    lines.push("");
    lines.push("<!-- expand: detailed-log -->");
    lines.push("<details>");
    lines.push("<summary>📋 Detailed log (click to expand)</summary>");
    lines.push("");
    lines.push("```");
    lines.push(escapedExcerpt);
    lines.push("```");
    lines.push("</details>");
  }

  if (errorDetails) {
    lines.push("");
    lines.push("<!-- expand: error-details -->");
    lines.push("<details>");
    lines.push("<summary>⚠️ Error details (click to expand)</summary>");
    lines.push("");
    lines.push("```");
    lines.push(escapeMarkdown(errorDetails));
    lines.push("```");
    lines.push("</details>");
  }

  lines.push("");
  lines.push("---");
  lines.push(`*Report generated by ChipAgent MCP — ${ts}*`);

  return lines.join("\n");
}

export function registerGenerateReport(server: McpServer): void {
  server.tool(
    "generate_report",
    "Generate a structured Markdown report file after a PnR stage execution",
    {
      stage: z.enum(["synth", "floorplan", "place", "cts", "route", "finish"]).describe(
        "ORFS stage name",
      ),
      module_name: z.string().describe("Design/module name (e.g. CPU8)"),
      success: z.boolean().describe("Whether the stage completed successfully"),
      exit_code: z.number().nullable().describe("Process exit code, or null if timed out"),
      metrics: z
        .record(z.string(), z.union([z.string(), z.number(), z.null()]))
        .optional()
        .describe("Optional key-value metrics to include in the report"),
      log_excerpt: z.string().optional().describe("Optional log excerpt (first/last lines) to include"),
      error_details: z.string().optional().describe("Optional error details for failed stages"),
    },
    async ({ stage, module_name, success, exit_code, metrics, log_excerpt, error_details }) => {
      const workspaceDir = resolveModuleWorkspace(module_name);

      if (!workspaceDir) {
        // No workspace configured — return report as text content instead
        const report = buildMarkdownReport({ stage, moduleName: module_name, success, exitCode: exit_code, metrics, logExcerpt: log_excerpt, errorDetails: error_details });
        return {
          content: [
            {
              type: "text" as const,
              text: JSON.stringify({ report_content: report, workspace_not_configured: true }),
            },
          ],
        };
      }

      const reportsDir = join(workspaceDir, "workspace", "reports");
      if (!existsSync(reportsDir)) {
        mkdirSync(reportsDir, { recursive: true });
      }

      const ts = timestamp();
      const reportFile = join(reportsDir, `pnr_${stage}_${ts}.md`);

      const report = buildMarkdownReport({
        stage,
        moduleName: module_name,
        success,
        exitCode: exit_code,
        metrics,
        logExcerpt: log_excerpt,
        errorDetails: error_details,
      });

      writeFileSync(reportFile, report, "utf-8");

      return {
        content: [
          {
            type: "text" as const,
            text: JSON.stringify({ report_file: reportFile, report_content: report }),
          },
        ],
      };
    },
  );
}
